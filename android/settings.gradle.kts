# Android starter app

This folder contains a minimal Android application skeleton for a Jarvis mobile client.

## Open in Android Studio

1. Open Android Studio.
2. Choose `Open an existing project`.
3. Select the `android/` folder.
4. Let Gradle sync.

## Notes

The starter app includes:
- app module setup
- basic Activity UI
- placeholder for assistant integration
- minimal Material 3 styling

